#!/usr/bin/env python3
"""Helper script to generate Fernet keys and encrypt secrets for .env.

Usage:
    python scripts/encrypt-secret.py key
        Generate a new Fernet key and print it. Set this as SECRET_KEY in .env.

    python scripts/encrypt-secret.py encrypt "your_password"
        Encrypt a plain-text value using the SECRET_KEY from .env or the
        --key flag, and print the encrypted token.

    python scripts/encrypt-secret.py encrypt "your_password" --key <fernet_key>
        Encrypt using an explicit key instead of .env.

Examples:
    # 1. Generate a new key
    python scripts/encrypt-secret.py key
    # Output: gAAAAABl... (copy this to SECRET_KEY in .env)

    # 2. Encrypt your Oracle GSYSTEM password
    python scripts/encrypt-secret.py encrypt "MySecureP@ssw0rd"
    # Output: gAAAAABl... (copy this to ORACLE_PASSWORD in .env)

    # 3. Encrypt using an explicit key (no .env needed)
    python scripts/encrypt-secret.py encrypt "MySecureP@ssw0rd" --key gAAAAABl...
"""

import argparse
import sys

from cryptography.fernet import Fernet


def generate_key() -> str:
    """Generate a new Fernet key."""
    key = Fernet.generate_key()
    print(key.decode("ascii"))
    print("\nSet this as SECRET_KEY in your .env file:")
    print(f'  SECRET_KEY={key.decode("ascii")}')


def encrypt_value(plain_text: str, key: str) -> str:
    """Encrypt a value using the given Fernet key."""
    fernet = Fernet(key.encode("ascii"))
    token = fernet.encrypt(plain_text.encode("utf-8"))
    return token.decode("ascii")


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Encrypt secrets for Oracle Sentinel AI .env file"
    )
    subparsers = parser.add_subparsers(dest="command", required=True)

    # Key generation
    key_parser = subparsers.add_parser("key", help="Generate a new Fernet key")

    # Encrypt
    encrypt_parser = subparsers.add_parser("encrypt", help="Encrypt a secret value")
    encrypt_parser.add_argument("value", help="Plain-text value to encrypt")
    encrypt_parser.add_argument(
        "--key",
        help="Fernet key (otherwise read from SECRET_KEY in .env)",
    )

    args = parser.parse_args()

    if args.command == "key":
        generate_key()

    elif args.command == "encrypt":
        # Determine the key
        key = args.key
        if key is None:
            # Try to read from .env
            try:
                from dotenv import load_dotenv, dotenv_values
                load_dotenv()
                values = dotenv_values()
                key = values.get("SECRET_KEY", "")
            except ImportError:
                pass

        if not key:
            print("Error: No key provided. Use one of:", file=sys.stderr)
            print("  1. Pass --key <fernet_key>", file=sys.stderr)
            print("  2. Set SECRET_KEY in .env", file=sys.stderr)
            print("  3. Run: python scripts/encrypt-secret.py key", file=sys.stderr)
            sys.exit(1)

        try:
            encrypted = encrypt_value(args.value, key)
            print(encrypted)
            print("\nSet this in your .env file:")
            print(f"  ORACLE_PASSWORD={encrypted}")
        except Exception as e:
            print(f"Error encrypting value: {e}", file=sys.stderr)
            print("Make sure the key is a valid Fernet key (generated by 'key' command).", file=sys.stderr)
            sys.exit(1)


if __name__ == "__main__":
    main()
